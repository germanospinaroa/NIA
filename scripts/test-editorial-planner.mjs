import assert from 'node:assert/strict';
import { buildEditorialMemory } from '../lib/server/editorial-memory.ts';
import { planEditorial } from '../lib/server/editorial-planner.ts';
const now = new Date('2026-10-03T12:00:00Z');
const base = Array.from({ length: 5 }, (_, i) => ({ id: String(i), created_at: new Date(now.getTime() - i * 86400000).toISOString(), topic: 'criterio propio', concept: 'aprobacion', angle: 'desacuerdo', intervention_type: 'step_by_step', depth: 'medium' }));
const memory = buildEditorialMemory(base, 30, now);
const refresh = planEditorial({ desiredChange: 'Confiar más en mi criterio', currentContext: 'Cuando cuestionan una decisión', communicationPreference: 'structured', memory, relevantTopics: ['criterio propio', 'límites'] });
assert.equal(refresh.strategy, 'refresh_topic');
assert.equal(refresh.recommended_topic, 'límites');
assert.notEqual(refresh.preferred_or_recommended_intervention_type, 'step_by_step');
const continuePlan = planEditorial({ desiredChange: 'Confiar más en mi criterio', currentContext: 'Cuando cuestionan una decisión', communicationPreference: 'idea', memory: buildEditorialMemory([], 30, now) });
assert.equal(continuePlan.strategy, 'continue_topic');
assert.equal(continuePlan.preferred_or_recommended_intervention_type, 'brief_insight');
console.log('editorial planner tests: PASS');
