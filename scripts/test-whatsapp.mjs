import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createLinkCode, extractLinkCode, hashLinkCode, maskPhone, whatsappDeepLink } from '../lib/server/whatsapp.ts';

const first = createLinkCode();
const second = createLinkCode();
assert.match(first, /^NIA-[A-Z0-9]{4}$/);
assert.match(second, /^NIA-[A-Z0-9]{4}$/);
assert.notEqual(first, second);
assert.equal(hashLinkCode(first), hashLinkCode(first.toLowerCase()));
assert.equal(extractLinkCode(`Hola NIA. Código: ${first}`), first);
assert.equal(extractLinkCode('Hola sin código'), null);
assert.equal(maskPhone('573001231234'), '+57 •••••••234');
const previous = process.env.WHATSAPP_BUSINESS_NUMBER;
process.env.WHATSAPP_BUSINESS_NUMBER = '573001231234';
assert.match(whatsappDeepLink(first), /^https:\/\/wa\.me\/573001231234\?text=/);
const linkRoute = fs.readFileSync(new URL('../app/api/whatsapp/link/route.ts', import.meta.url), 'utf8');
const webhookRoute = fs.readFileSync(new URL('../app/api/whatsapp/webhook/route.ts', import.meta.url), 'utf8');
assert.match(linkRoute, /createAdminClient/);
assert.match(linkRoute, /code, deep_link/);
assert.match(webhookRoute, /sendWhatsAppText/);
const previousProvider = process.env.WHATSAPP_PROVIDER;
const previousUrl = process.env.EVOLUTION_API_URL;
const previousKey = process.env.EVOLUTION_API_KEY;
const previousInstance = process.env.EVOLUTION_INSTANCE;
process.env.WHATSAPP_PROVIDER = 'evolution';
process.env.EVOLUTION_API_URL = 'https://evolution.example.com';
process.env.EVOLUTION_API_KEY = 'test-key';
process.env.EVOLUTION_INSTANCE = 'NIA';
const originalFetch = globalThis.fetch;
globalThis.fetch = async (url, init) => {
  assert.equal(url, 'https://evolution.example.com/message/sendText/NIA');
  assert.equal(init.headers.apikey, 'test-key');
  assert.deepEqual(JSON.parse(init.body), { number: '573001231234', text: 'hello' });
  return new Response(JSON.stringify({ key: { id: 'provider-id' } }), { status: 201, headers: { 'content-type': 'application/json' } });
};
const { sendWhatsAppText } = await import('../lib/server/whatsapp.ts');
const delivered = await sendWhatsAppText('+57 300 123 1234', 'hello');
assert.deepEqual(delivered, { ok: true, status: 201, providerMessageId: 'provider-id' });
globalThis.fetch = async () => new Response(JSON.stringify({ message: 'instance not found' }), { status: 404, headers: { 'content-type': 'application/json' } });
const rejected = await sendWhatsAppText('573001231234', 'hello');
assert.equal(rejected.ok, false);
assert.equal(rejected.status, 404);
globalThis.fetch = async () => new Response(JSON.stringify({ error: 'provider unavailable' }), { status: 500, headers: { 'content-type': 'application/json' } });
const serverRejected = await sendWhatsAppText('573001231234', 'hello');
assert.equal(serverRejected.ok, false);
assert.equal(serverRejected.status, 500);
globalThis.fetch = async () => { throw new Error('network down'); };
const networkRejected = await sendWhatsAppText('573001231234', 'hello');
assert.deepEqual(networkRejected, { ok: false, reason: 'network_error' });
delete process.env.EVOLUTION_API_URL;
const notConfigured = await sendWhatsAppText('573001231234', 'hello');
assert.deepEqual(notConfigured, { ok: false, reason: 'not_configured' });
globalThis.fetch = originalFetch;
if (previousProvider === undefined) delete process.env.WHATSAPP_PROVIDER; else process.env.WHATSAPP_PROVIDER = previousProvider;
if (previousUrl === undefined) delete process.env.EVOLUTION_API_URL; else process.env.EVOLUTION_API_URL = previousUrl;
if (previousKey === undefined) delete process.env.EVOLUTION_API_KEY; else process.env.EVOLUTION_API_KEY = previousKey;
if (previousInstance === undefined) delete process.env.EVOLUTION_INSTANCE; else process.env.EVOLUTION_INSTANCE = previousInstance;
if (previous === undefined) delete process.env.WHATSAPP_BUSINESS_NUMBER; else process.env.WHATSAPP_BUSINESS_NUMBER = previous;
console.log('whatsapp contract tests: PASS');
