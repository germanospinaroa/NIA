import assert from 'node:assert/strict';
import fs from 'node:fs';

for (const file of ['app/privacidad/page.tsx', 'app/terminos/page.tsx', 'app/cancelacion/page.tsx']) assert.ok(fs.existsSync(file), `${file} exists`);
const privacy = fs.readFileSync('app/privacidad/page.tsx', 'utf8');
const terms = fs.readFileSync('app/terminos/page.tsx', 'utf8');
const cancellation = fs.readFileSync('app/cancelacion/page.tsx', 'utf8');
const plans = fs.readFileSync('app/descubre/planes/page.tsx', 'utf8');
assert.match(privacy, /nombre preferido/);
assert.match(privacy, /WhatsApp/);
assert.match(privacy, /Hotmart/);
assert.match(privacy, /tarjeta/);
assert.match(privacy, /app\/tu#soporte/);
assert.match(terms, /no es terapia/);
assert.match(terms, /US\$4\.99 al mes/);
assert.match(terms, /US\$49\.99 al año/);
assert.match(terms, /7 días/);
assert.match(terms, /renueva automáticamente/);
assert.match(cancellation, /Cancelar suscripción/);
assert.match(cancellation, /app\/tu/);
assert.match(cancellation, /cada mes/);
assert.match(cancellation, /cada año/);
assert.match(plans, /href="\/privacidad"/);
assert.match(plans, /href="\/terminos"/);
assert.match(plans, /href="\/cancelacion"/);
assert.match(plans, /se renueva automáticamente después de la prueba gratuita/);
assert.match(plans, /<del>US\$6\.99<\/del>/);
assert.match(plans, /US\$4\.99/);
assert.doesNotMatch(`${privacy}\n${terms}\n${cancellation}\n${plans}`, /germanospinaroa@gmail\.com/);
assert.doesNotMatch(fs.readFileSync('components/funnel/PremiumDiscover.tsx', 'utf8'), /Ver fuentes/);
console.log('legal page tests: PASS');
