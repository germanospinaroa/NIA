import assert from 'node:assert/strict';
import fs from 'node:fs';
import { dueSlots, localClock } from '../lib/server/whatsapp-schedule.ts';
import { composeNiaMessage, closingFor, greetingFor, timeOfDay } from '../lib/server/message-composer.ts';

const profile = { timezone: 'America/Bogota', message_frequency: 1, message_time_1: '08:00', message_time_2: null };
const morning = new Date('2026-10-03T13:05:00.000Z');
assert.deepEqual(localClock('America/Bogota', morning), { hour: 8, minute: 5, date: '2026-10-03' });
assert.deepEqual(dueSlots(profile, morning), [{ slot: '1', localDate: '2026-10-03' }]);
assert.deepEqual(dueSlots(profile, new Date('2026-10-03T13:14:00.000Z')), [{ slot: '1', localDate: '2026-10-03' }]);
assert.deepEqual(dueSlots(profile, new Date('2026-10-03T13:15:00.000Z')), []);
assert.deepEqual(dueSlots({ ...profile, message_frequency: 2, message_time_2: '18:00' }, new Date('2026-10-03T23:05:00.000Z')), [{ slot: '2', localDate: '2026-10-03' }]);
assert.equal(timeOfDay(new Date('2026-10-03T13:00:00.000Z'), 'America/Bogota'), 'morning');
assert.equal(timeOfDay(new Date('2026-10-03T18:00:00.000Z'), 'America/Bogota'), 'afternoon');
assert.equal(timeOfDay(new Date('2026-10-04T01:00:00.000Z'), 'America/Bogota'), 'night');
assert.match(greetingFor('Adriana', morning, 'America/Bogota', 'fixture-user'), /Adriana|Buenos días/);
assert.equal(greetingFor(null, morning, 'America/Bogota', 'fixture-user'), 'Buenos días.');
const fixtureContent = 'Cuando aparezca la duda, vuelve a revisar qué cambió realmente antes de tomar otra decisión.';
const fixtureMessage = composeNiaMessage({ content: fixtureContent, firstName: 'Adriana', timezone: 'America/Bogota', userKey: 'fixture-user', now: morning });
assert.match(fixtureMessage, /Adriana|Buenos días/);
assert.match(fixtureMessage, /qué cambió realmente/);
assert.equal(fixtureMessage.split(/\n\n/).length, 3);
const fixtureClosing = closingFor(fixtureContent, morning, 'America/Bogota', 'fixture-user');
assert.notEqual(closingFor(fixtureContent, new Date(morning.getTime() + 86_400_000), 'America/Bogota', 'fixture-user', [fixtureClosing]), fixtureClosing);
const route = fs.readFileSync(new URL('../app/api/cron/daily-whatsapp/route.ts', import.meta.url), 'utf8');
const delivery = fs.readFileSync(new URL('../lib/server/whatsapp-daily.ts', import.meta.url), 'utf8');
assert.match(route, /CRON_SECRET/);
assert.match(delivery, /whatsapp_daily_deliveries/);
assert.match(delivery, /providerMessageId/);
assert.match(delivery, /claim_token/);
assert.match(delivery, /daily_whatsapp_schema_missing/);
assert.match(delivery, /status: 'pending'/);
assert.match(delivery, /status: 'sent'/);
assert.match(delivery, /status: 'failed'/);
assert.match(delivery, /locked_until: null/);
assert.match(delivery, /claim_token: null/);
assert.match(delivery, /getOrCreateDailyInteraction\(admin, profile\.id, 'whatsapp', now, due\.slot\)/);
assert.match(delivery, /for \(const due of slots\)/);
assert.match(delivery, /interactionId: String\(daily\.interaction\.id\)/);
assert.match(delivery, /dryRun/);
assert.match(delivery, /eq\('locked_until', current\.locked_until\)/);
assert.match(delivery, /\.is\('locked_until', null\)/);
assert.match(delivery, /getOrCreateDailyInteraction\(admin, profile\.id, 'whatsapp', now, due\.slot\)/);
assert.equal((delivery.match(/getOrCreateDailyInteraction\(admin, profile\.id, 'whatsapp', now, due\.slot\)/g) || []).length, 1);
assert.match(delivery, /for \(const due of slots\) \{/);
assert.match(delivery, /claimExistingFailedDelivery/);
assert.match(delivery, /sendClaimedDelivery/);
const retryRoute = fs.readFileSync(new URL('../app/api/admin/daily-whatsapp/retry/route.ts', import.meta.url), 'utf8');
assert.match(retryRoute, /CRON_SECRET/);
assert.match(retryRoute, /delivery_id/);
assert.doesNotMatch(retryRoute, /getOrCreateDailyInteraction/);
assert.match(retryRoute, /status: 'already_sent'/);
assert.match(retryRoute, /sendClaimedDelivery/);
console.log('daily whatsapp tests: PASS');
